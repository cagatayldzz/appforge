/// The name of a territory as App Store Connect shows it; the code itself when it is not known.
pub fn territory_name(code: &str) -> &str {
  NAMES.binary_search_by(|(known, _)| known.cmp(&code)).map_or(code, |index| NAMES[index].1)
}

/// The code of the territory with this name or code, ignoring case.
pub fn territory_code(text: &str) -> Option<&'static str> {
  let text = text.trim();
  NAMES.iter().find(|(code, name)| code.eq_ignore_ascii_case(text) || name.eq_ignore_ascii_case(text)).map(|(code, _)| *code)
}
